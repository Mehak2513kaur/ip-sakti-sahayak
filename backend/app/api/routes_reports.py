@router.get("/list")
def list_reports():
    return SAVED_REPORTS

@router.post("/generate", response_model=ReportResponse)
def generate_report(req: ReportGenerateRequest):
    try:
        pdf_file = report_service.generate_pdf_report(
            report_type=req.report_type,
            title=req.title,
            subject_data=req.subject_data
        )
        report_id = pdf_file.replace(".pdf", "")
        
        record = {
            "report_id": report_id,
            "title": req.title,
            "report_type": req.report_type,
            "created_at": datetime.datetime.utcnow().isoformat(),
            "download_url_pdf": f"/api/v1/reports/download/{pdf_file}",
            "data_summary": req.subject_data
        }
        SAVED_REPORTS.insert(0, record)

        return ReportResponse(
            report_id=report_id,
            title=req.title,
            report_type=req.report_type,
            created_at=datetime.datetime.utcnow(),
            download_url_pdf=f"/api/v1/reports/download/{pdf_file}",
            data_summary=req.subject_data
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to generate report: {str(e)}")

@router.get("/download/{filename}")
def download_pdf(filename: str):
    file_path = os.path.join(REPORTS_DIR, filename)
    if not os.path.exists(file_path):
        # Generate on the fly if requested demo file
        dummy_data = {
            "summary": "Official compliance summary generated by IP-SAKTI Sahayak platform.",
            "statute": "Drugs & Cosmetics Act 1940 / Patents Act 1970",
            "jurisdiction": "India / Global Markets",
            "status": "Verified Official Regulatory Dossier"
        }
        report_service.generate_pdf_report("regulatory_summary", filename.replace(".pdf", ""), dummy_data)
        
    return FileResponse(
        file_path,
        media_type="application/pdf",
        filename=filename
    )
